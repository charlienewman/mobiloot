#!/usr/bin/env python3
"""Regenerates everything derived from the logo in logo/:
  - app/components/brand-paths.ts  (vector paths the app draws with react-native-svg)
  - app/assets/images/*.png        (launcher icon, adaptive icon layers, splash, favicon)
Needs google-chrome (used headless to rasterise the SVGs) and Pillow.
    python3 scripts/brand-assets.py
"""
import re, subprocess, tempfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BG = "#0C0D10"
STOPS = [("0%", "#D7FF44"), ("50%", "#1FE4D7"), ("100%", "#9C46FD")]

svg = (ROOT / "logo/mobiloot-wordmark.svg").read_text()
word_d, loop_d = re.findall(r'<path fill="[^"]+" d="([^"]+)"', svg)


def bbox(d):
    n = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", d)]
    xs, ys = n[0::2], n[1::2]
    return min(xs), min(ys), max(xs), max(ys)


lx0, ly0, lx1, ly1 = bbox(loop_d)
wx0, wy0, wx1, wy1 = bbox(word_d + " " + loop_d)
r = lambda v: round(v, 1)

(ROOT / "app/components/brand-paths.ts").write_text(
    "// Generated by scripts/brand-assets.py from logo/mobiloot-wordmark.svg. Do not edit by hand.\n"
    f"export const LOOP_BOX = {{ x: {r(lx0)}, y: {r(ly0)}, w: {r(lx1 - lx0)}, h: {r(ly1 - ly0)} }} as const\n"
    f"export const WORD_BOX = {{ x: {r(wx0)}, y: {r(wy0)}, w: {r(wx1 - wx0)}, h: {r(wy1 - wy0)} }} as const\n"
    f"export const LOOP_PATH =\n  '{loop_d}'\n"
    f"export const LETTERS_PATH =\n  '{word_d}'\n"
)


def loop_svg(px, loop_frac, fill=None, bg=None):
    """Square canvas of `px`, loop centred, loop width = loop_frac of the canvas."""
    side = (lx1 - lx0) / loop_frac
    cx, cy = (lx0 + lx1) / 2, (ly0 + ly1) / 2
    vb = f"{cx - side / 2} {cy - side / 2} {side} {side}"
    stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in STOPS)
    rect = f'<rect x="{cx - side / 2}" y="{cy - side / 2}" width="{side}" height="{side}" fill="{bg}"/>' if bg else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="{vb}">'
        f'<defs><linearGradient id="g" gradientUnits="userSpaceOnUse" x1="{lx0}" y1="0" x2="{lx1}" y2="0">{stops}</linearGradient></defs>'
        f'{rect}<path fill="{fill or "url(#g)"}" d="{loop_d}"/></svg>'
    )


def render(svg_text, out, px):
    with tempfile.TemporaryDirectory() as tmp:
        html = Path(tmp) / "a.html"
        html.write_text(f"<!doctype html><style>html,body{{margin:0;background:transparent}}svg{{display:block}}</style>{svg_text}")
        subprocess.run(
            ["google-chrome", "--headless=new", "--no-sandbox", "--hide-scrollbars", "--force-device-scale-factor=1",
             "--default-background-color=00000000", f"--window-size={px},{px}", f"--screenshot={out}", html.as_uri()],
            check=True, capture_output=True,
        )
    im = Image.open(out)
    assert im.size == (px, px), im.size
    return im


IMG = ROOT / "app/assets/images"
render(loop_svg(1024, 0.62, bg=BG), IMG / "icon.png", 1024).convert("RGB").save(IMG / "icon.png")
# Adaptive icon: only the middle 66/108 of the layer is guaranteed visible, so keep the loop inside it.
render(loop_svg(1024, 0.46), IMG / "android-icon-foreground.png", 1024)
render(loop_svg(1024, 0.46, fill="#FFFFFF"), IMG / "android-icon-monochrome.png", 1024)
Image.new("RGB", (1024, 1024), BG).save(IMG / "android-icon-background.png")
render(loop_svg(1024, 0.92), IMG / "splash-icon.png", 1024)
render(loop_svg(96, 0.8, bg=BG), IMG / "favicon.png", 96).convert("RGB").save(IMG / "favicon.png")
print("ok", r(lx0), r(ly0), r(lx1), r(ly1), "| word", r(wx0), r(wy0), r(wx1), r(wy1))
